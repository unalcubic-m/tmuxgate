_BACKUP_NAME = re.compile(
    r"\A(?P<kind>.+?)-(?P<stamp>\d{8}T\d{6}Z)-(?P<token>[0-9a-f]{8})(?P<suffix>\.[A-Za-z0-9]+)?\Z"
)


def _releases_in_use(releases: Path) -> set[str]:
    """Release IDs a live process is still running from.

    Removing a release out from under a running tmuxgate would break every
    module it has not imported yet, so retention has to leave those alone.  This
    only reads ``/proc`` entries this user can already see; it never signals,
    starts, or stops anything.  A ``/proc`` that cannot be listed at all is
    reported by raising, because pruning without this evidence is not safe.
    """

    in_use: set[str] = set()
    root = releases.resolve()
    for entry in Path("/proc").iterdir():
        if not entry.name.isdigit():
            continue
        try:
            target = Path(os.readlink(entry / "exe")).resolve()
        except OSError:
            # Another user's process, or one that exited between the listing
            # and the read.  Neither can be running from our releases.
            continue
        try:
            relative = target.relative_to(root)
        except ValueError:
            continue
        if relative.parts:
            in_use.add(relative.parts[0])
    return in_use


def _release_age_key(path: Path) -> tuple[str, int, str]:
    """Sort key ordering releases oldest first.

    A release ID begins with a UTC timestamp, which is the authoritative order,
    but it is only second-granular: installs within one second differ solely by
    their random suffix and would otherwise sort arbitrarily.  Directory
    creation time breaks those ties, and the full name makes the order total.
    """

    try:
        created = path.stat().st_mtime_ns
    except OSError:
        created = 0
    return (path.name[:16], created, path.name)


def _prune_releases(releases: Path, *, keep: int, protected: set[str]) -> list[str]:
    """Delete surplus releases, newest kept first; return what was removed.

    ``protected`` holds the releases that must survive whatever ``keep`` says:
    the active one, the one ``current`` pointed at before this run, and anything
    still in use.
    """

    if keep <= 0:
        return []
    existing = sorted(
        (path for path in releases.iterdir() if path.is_dir()),
        key=_release_age_key,
        reverse=True,
    )
    removed: list[str] = []
    kept = 0
    for path in existing:
        if path.name in protected:
            kept += 1
            continue
        if kept < keep:
            kept += 1
            continue
        shutil.rmtree(path)
        removed.append(path.name)
    return removed


def _prune_backups(backups: Path, *, keep: int) -> list[str]:
    """Delete surplus pre-images per backup kind; return what was removed.

    The oldest pre-image of each kind is always kept.  It is the only copy of
    the file as it was before tmuxgate ever managed it, so it is what a user
    needs to undo the integration completely; every later one is a pre-image of
    an already-managed file.
    """

    if keep <= 0:
        return []
    kinds: dict[str, list[Path]] = {}
    for path in backups.iterdir():
        if not path.is_file():
            continue
        matched = _BACKUP_NAME.fullmatch(path.name)
        if matched is None:
            # Not written by this installer; never remove it.
            continue
        kinds.setdefault(matched.group("kind"), []).append(path)
    removed: list[str] = []
    for group in kinds.values():
        group.sort(key=lambda path: path.name)
        surplus = group[1:-keep] if keep < len(group) else []
        for path in surplus:
            path.unlink()
            removed.append(path.name)
    return removed


def _active_release_identity_from(snapshot: FileSnapshot) -> str | None:
    """The release ID a captured ``current`` symlink pointed at, if any."""

    if not snapshot.exists or snapshot.kind != "symlink":
        return None
    return PurePosixPath(snapshot.target).name or None


def _active_release_identity(install_root: Path) -> str | None:
    """The release ID ``current`` points at, or ``None`` when there is none."""

    try:
        target = os.readlink(install_root / "current")
    except OSError:
        return None
    name = PurePosixPath(target).name
    return name or None


def install(args: argparse.Namespace, report: InstallReport | None = None) -> int:
    if report is None:
        report = InstallReport()
    if sys.version_info < (3, 11):
        raise InstallError("Python 3.11 or newer is required", report=report)
    if platform.system() != "Linux":
        raise InstallError("tmuxgate's installer currently supports Linux only")
    if os.geteuid() == 0:
        raise InstallError("do not run the tmuxgate installer as root or with sudo")
    os.umask(0o077)

    if args.keep_releases < 0:
        raise InstallError("--keep-releases must be 0 or greater", report=report)
    source = args.source.resolve()
    if not (source / "pyproject.toml").is_file() or not (source / "src" / "tmuxgate").is_dir():
        raise InstallError(f"not a tmuxgate source tree: {source}")
    home = Path.home()
    data_home = _select_base(os.environ, "XDG_DATA_HOME", home / ".local" / "share")
    config_home = _select_base(os.environ, "XDG_CONFIG_HOME", home / ".config")
    install_root = data_home / "tmuxgate"
    releases = install_root / "releases"
    backups = install_root / "backups"
    bin_dir = args.bin_dir or home / ".local" / "bin"
    if not bin_dir.is_absolute():
        raise InstallError("--bin-dir must be absolute")
    launcher = bin_dir / "tmuxgate"

    _ensure_private_directory(install_root)
    _ensure_private_directory(releases)
    _ensure_private_directory(backups)
    _ensure_user_directory(bin_dir)
    report.active_identity = _active_release_identity(install_root)
    if report.active_identity is None:
        report.active_release = "ABSENT"
    if not launcher_is_replaceable(
        launcher,
        source=source,
        install_root=install_root,
        replace_existing=args.replace_existing,
    ):
        raise InstallError(
            f"refusing to replace unrelated launcher {launcher}; use --replace-existing"
        )

    lock_path = install_root / "install.lock"
    lock_flags = os.O_RDWR | os.O_CREAT | getattr(os, "O_CLOEXEC", 0) | getattr(os, "O_NOFOLLOW", 0)
    lock_descriptor = os.open(lock_path, lock_flags, 0o600)
    release_dir: Path | None = None
    rollback: list[OwnedMutation] = []
    published = False
    committed = False
    try:
        os.fchmod(lock_descriptor, 0o600)
        try:
            fcntl.flock(lock_descriptor, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as exc:
            raise InstallError("another tmuxgate installer is already running") from exc

        config_path = config_home / "tmuxgate" / "config.toml"
        config_before = FileSnapshot.capture(config_path)
        if not config_before.exists:
            raise InstallError(
                f"configuration not found: {config_path}; create and validate it before installing"
            )
        if config_before.kind != "file":
            raise InstallError(f"refusing non-regular tmuxgate configuration: {config_path}")
        release_id = dt.datetime.now(dt.UTC).strftime("%Y%m%dT%H%M%SZ") + "-" + secrets.token_hex(4)
        release_dir = releases / release_id
        release_dir.mkdir(mode=0o700)
        report.candidate_identity = release_id
        report.candidate_release = "STAGING"
        venv_python = release_dir / "bin" / "python"
        venv_tmuxgate = release_dir / "bin" / "tmuxgate"

        _run(
            (sys.executable, "-m", "venv", str(release_dir)),
            label="creating isolated Python environment",
        )
        pip_env = dict(os.environ)
        pip_env["PIP_DISABLE_PIP_VERSION_CHECK"] = "1"
        _run(
            (
                str(venv_python),
                "-m",
                "pip",
                "install",
                "--no-input",
                "--no-cache-dir",
                str(source),
            ),
            env=pip_env,
            label="installing tmuxgate and runtime dependencies",
        )
        _run(
            (
                str(venv_python),
                "-c",
                "import mcp, textual, uvicorn, tmuxgate, tmuxgate.textual_interface",
            ),
            capture=True,
            label="verifying installed Python imports",
        )
        _run((str(venv_tmuxgate), "--version"), capture=True, label="checking installed version")
        _run((str(venv_tmuxgate), "--help"), capture=True, label="checking installed CLI")
        _run(
            (str(venv_tmuxgate), "--config", str(config_path), "config", "check"),
            capture=True,
            label="validating existing tmuxgate configuration",
        )
        report.candidate_release = "VERIFIED"
        report.configuration = "PASSED"

        probe_command = [str(venv_python), str(source / "scripts" / "install.py"), "--installed-probe"]
        probe_command.extend(("--config", str(config_path)))
        probe = _run(probe_command, capture=True, label="preparing tmuxgate MCP credential")
        try:
            probe_result = ProbeResult.from_json(json.loads(probe.stdout))
        except json.JSONDecodeError as exc:
            raise InstallError("installed tmuxgate probe returned invalid JSON") from exc
        report.mcp_credential = (
            "CREATED AND RETAINED" if probe_result.token_created else "PRE-EXISTING"
        )
        if FileSnapshot.capture(config_path) != config_before:
            report.configuration = "CHANGED CONCURRENTLY"
            raise InstallError(
                "existing tmuxgate configuration changed during installation",
                report=report,
            )
        if (
            not args.no_codex
            and probe_result.approval_mode == "disabled"
            and not args.allow_disabled_approvals
        ):
            report.next_action = (
                "Set approval_mode to 'always' in "
                f"{config_path}, or rerun with --allow-disabled-approvals if "
                "disabled approvals are intentional."
            )
            raise InstallError(
                "approval_mode is disabled; review the security impact and rerun with "
                "--allow-disabled-approvals, or set approval_mode to 'always'",
                report=report,
            )

        if args.no_codex:
            report.codex_registration = "SKIPPED"
            report.shell_integration = "SKIPPED"
        elif args.no_shell_integration:
            report.shell_integration = "SKIPPED"

        if not args.no_codex:
            codex = args.codex_bin or (Path(found) if (found := shutil.which("codex")) else None)
            if codex is None:
                raise InstallError("Codex CLI was not found; use --no-codex to skip registration")
            if not codex.is_absolute():
                raise InstallError("--codex-bin must be absolute")
            codex_home = _select_base(os.environ, "CODEX_HOME", home / ".codex")
            _ensure_codex_directory(codex_home)
            codex_config = codex_home / "config.toml"
            codex_mutation = _register_codex(
                codex,
                codex_config,
                url=probe_result.mcp_url,
                replace_conflict=args.replace_codex,
                backup_dir=backups,
            )
            report.codex_registration = (
                "UNCHANGED" if codex_mutation is None else "UPDATED"
            )
            if codex_mutation is not None:
                rollback.append(codex_mutation)

        if not args.no_codex and not args.no_shell_integration:
            shell_config_dir = config_home / "tmuxgate"
            _ensure_private_directory(shell_config_dir)
            env_file = shell_config_dir / "codex-env.sh"
            shell = Path(os.environ.get("SHELL", "")).name
            if shell not in {"bash", ""}:
                raise InstallError(
                    f"automatic shell integration supports Bash, not {shell!r}; use --no-shell-integration"
                )
            profiles = (home / ".bashrc", home / ".profile")
            profile_mutations = _write_shell_integration(
                env_file,
                profiles,
                token_path=probe_result.token_path,
                backup_dir=backups,
            )
            report.shell_integration = (
                "UNCHANGED" if not profile_mutations else "UPDATED"
            )
            rollback.extend(profile_mutations)

        current = install_root / "current"
        current_before = FileSnapshot.capture(current)
        launcher_before = FileSnapshot.capture(launcher)
        if not launcher_snapshot_is_replaceable(
            launcher_before,
            launcher=launcher,
            source=source,
            install_root=install_root,
            replace_existing=args.replace_existing,
        ):
            raise InstallError(
                f"refusing launcher changed during installation: {launcher}; "
                "use --replace-existing on a fresh run"
            )
        # From this point a process could observe the new release even if a
        # directory fsync or later step fails, so failure cleanup must retain it.
        published = True
        report.publication = "IN PROGRESS"
        current_mutation = _symlink_owned(
            current,
            f"releases/{release_id}",
            before=current_before,
        )
        if current_mutation is not None:
            rollback.append(current_mutation)
        launcher_mutation = _symlink_owned(
            launcher,
            str(current / "bin" / "tmuxgate"),
            before=launcher_before,
        )
        if launcher_mutation is not None:
            rollback.append(launcher_mutation)

        manifest = {
            "installer_version": INSTALLER_VERSION,
            "installed_at": dt.datetime.now(dt.UTC).isoformat(),
            "source": str(source),
            "mcp_url": probe_result.mcp_url,
            "launcher": str(launcher),
        }
        manifest_path = install_root / "install.json"
        manifest_mutation = _write_owned(
            manifest_path,
            (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8"),
            0o600,
        )
        if manifest_mutation is not None:
            rollback.append(manifest_mutation)
        committed = True
        rollback.clear()
        release_dir = None

        # Retention runs only here: the new release is published, the manifest
        # is written, and rollback has been cleared, so nothing left to undo can
        # need a directory this removes.  It still holds the install lock, so no
        # concurrent installer can be staging into the same directory.  A
        # failure to reclaim space must never fail an install that succeeded.
        pruned_releases: list[str] = []
        pruned_backups: list[str] = []
        try:
            protected = {release_id} | _releases_in_use(releases)
            previous = _active_release_identity_from(current_before)
            if previous is not None:
                # The target of the symlink rollback would restore, so removing
                # it would turn a later failed install into a dangling launcher.
                protected.add(previous)
            pruned_releases = _prune_releases(
                releases, keep=args.keep_releases, protected=protected
            )
            pruned_backups = _prune_backups(backups, keep=args.keep_releases)
        except BaseException as prune_error:
            print(
                f"tmuxgate installer: retention warning: {prune_error}",
                file=sys.stderr,
            )
            report.retention = "FAILED; NOTHING REMOVED"
        else:
            if pruned_releases or pruned_backups:
                report.retention = (
                    f"{len(pruned_releases)} release(s), "
                    f"{len(pruned_backups)} backup(s) removed"
                )
            else:
                report.retention = "NOTHING TO REMOVE"

        report.candidate_release = "PUBLISHED AS ACTIVE"
        report.publication = "COMPLETE"
        report.active_release = "UPDATED"
        report.active_identity = release_id
        report.overall = "COMPLETE"
        report.next_action = (
            "Start the foreground application in its controlling terminal with: tmuxgate"
        )

        print()
        print(f"tmuxgate installed: {launcher}")
        print(f"Active release: {release_id}")
        # A retained-after-failure release is a deliberate forensic artifact, so
        # retention names every directory it removes rather than reclaiming
        # space quietly.
        for name in pruned_releases:
            print(f"Removed superseded release: {name}")
        if pruned_backups:
            print(f"Removed superseded backups: {len(pruned_backups)}")
        print(f"Codex MCP endpoint: {probe_result.mcp_url}")
        print("The application was not started in the background.")
        if not args.no_codex:
            if args.no_shell_integration:
                print(f"Before launching Codex, export {MCP_TOKEN_ENV} from {probe_result.token_path}.")
            else:
                print("Open a new Bash shell and restart Codex so it inherits the MCP token.")
        print("Start the foreground application in its controlling terminal with: tmuxgate")
        if probe_result.approval_mode == "disabled":
            print(
                "WARNING: approval_mode is disabled; possession of the MCP token permits execution "
                "without a per-request terminal approval.",
                file=sys.stderr,
            )
        return 0
    except BaseException:
        if committed:
            raise
        attempted_rollback = bool(rollback)
        rollback_errors: list[str] = []
        for mutation in reversed(rollback):
            try:
                mutation.rollback()
            except Exception as rollback_error:
                rollback_errors.append(f"{mutation.path}: {rollback_error}")
        for error in rollback_errors:
            print(f"tmuxgate installer: rollback warning: {error}", file=sys.stderr)
        if rollback_errors:
            report.rollback = "INCOMPLETE"
            report.overall = "MANUAL RECOVERY REQUIRED"
        elif attempted_rollback:
            report.rollback = "COMPLETE"
        if (
            release_dir is not None
            and not published
            and release_dir.parent == releases
            and release_dir.exists()
        ):
            shutil.rmtree(release_dir)
            report.candidate_release = {
                "VERIFIED": "VERIFIED, THEN DISCARDED",
                "STAGING": "FAILED, THEN DISCARDED",
            }.get(report.candidate_release, "DISCARDED")
        elif release_dir is not None and published:
            print(
                f"tmuxgate installer: retaining published release after failure: {release_dir}",
                file=sys.stderr,
            )
            report.candidate_release = "RETAINED, NOT ACTIVE"
        # Nothing below the commit point ran, so whatever was active still is.
        if report.publication != "NOT ATTEMPTED":
            report.publication = (
                "ROLLED BACK" if not rollback_errors else "UNCERTAIN"
            )
        if report.active_release != "ABSENT":
            report.active_release = "UNCHANGED" if not rollback_errors else "UNCERTAIN"
        for stage in ("codex_registration", "shell_integration"):
            if getattr(report, stage) == "UPDATED":
                setattr(
                    report, stage, "RESTORED" if not rollback_errors else "UNCERTAIN"
                )
        raise
    finally:
        os.close(lock_descriptor)


def main(argv: Sequence[str] | None = None) -> int:
    selected = list(sys.argv[1:] if argv is None else argv)
    if selected and selected[0] == "--installed-probe":
        return _installed_probe(selected[1:])
    args = _public_parser().parse_args(selected)
    report = InstallReport()
    try:
        return install(args, report)
    except InstallError as exc:
        print(f"tmuxgate installer: {exc}", file=sys.stderr)
        # The reason comes first, then the state it left behind, so a run that
        # stopped early can never be mistaken for one that published a release.
        print((exc.report or report).render(), file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("tmuxgate installer: interrupted; previous installation retained", file=sys.stderr)
        return 130


if __name__ == "__main__":
    raise SystemExit(main())
